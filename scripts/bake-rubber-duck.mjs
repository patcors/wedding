// Offline recipe: the far rubber ducks' geometry (simplifiedRubberDuck(.1) in
// rubberDuckGeometry.ts), worked out once here rather than on every load,
// where simplifying the full duck took about half a second on a slow phone.
// Writes src/components/garden/rubberDuckBaked.ts. Re-run after changing the duck:
//   node scripts/bake-rubber-duck.mjs
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const { computeSimplifiedRubberDuck } = await import('../src/components/garden/rubberDuckGeometry.ts');
const KEEP = .1;
const geometry = computeSimplifiedRubberDuck(KEEP);
const encode = array => Buffer.from(array.buffer, array.byteOffset, array.byteLength).toString('base64');
const attributes = Object.fromEntries(Object.entries(geometry.attributes).map(([name, attribute]) => {
  if (!(attribute.array instanceof Float32Array) || attribute.normalized) throw new Error(`${name} is not plain float`);
  return [name, { size: attribute.itemSize, data: encode(attribute.array) }];
}));
const index = geometry.index.array;
if (!(index instanceof Uint16Array) && !(index instanceof Uint32Array)) throw new Error('unexpected index type');
const source = `// Generated by scripts/bake-rubber-duck.mjs from simplifiedRubberDuck(${KEEP}) in
// rubberDuckGeometry.ts; do not edit. tests/rubberDuck.test.mjs checks it still matches.
export const BAKED_DUCK = {
  keep: ${KEEP},
  attributes: ${JSON.stringify(attributes, null, 2).replace(/\n/g, '\n  ')},
  index: { type: '${index instanceof Uint16Array ? 'uint16' : 'uint32'}', data: '${encode(index)}' },
} as const;
`;
await writeFile(fileURLToPath(new URL('../src/components/garden/rubberDuckBaked.ts', import.meta.url)), source);
console.log('baked duck:', geometry.attributes.position.count, 'vertices,', index.length / 3, 'triangles,', source.length, 'bytes');
